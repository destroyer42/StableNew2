"""Explicit, bounded public-source lookups. Returned material is candidate data only."""

from __future__ import annotations

import json
import re
import time
from collections.abc import Callable
from dataclasses import dataclass
from typing import Any
from urllib.error import HTTPError
from urllib.request import HTTPRedirectHandler, Request, build_opener

from src.generation_profiles.evidence_catalog import MAX_BYTES


@dataclass(frozen=True)
class Lookup:
    service: str
    identifier: str
    revision: str = ""

    def __post_init__(self) -> None:
        if self.service == "civitai":
            valid = bool(re.fullmatch(r"[0-9a-f]{64}", self.identifier) and not self.revision)
        elif self.service == "huggingface":
            valid = bool(
                re.fullmatch(r"[A-Za-z0-9_-]{1,96}/[A-Za-z0-9_.-]{1,96}", self.identifier)
                and re.fullmatch(r"[0-9a-f]{40}", self.revision)
            )
        else:
            valid = False
        if not valid or ".." in self.identifier:
            raise ValueError("Lookup requires an exact public repository/revision or verified hash")

    @property
    def disclosure(self) -> str:
        return (
            f"Send {self.identifier}"
            + (f" at revision {self.revision}" if self.revision else "")
            + f" to {self.service}. No model bytes, prompts, images, ratings or local paths are sent."
        )

    @property
    def url(self) -> str:
        if self.service == "civitai":
            return f"https://civitai.com/api/v1/model-versions/by-hash/{self.identifier}"
        return f"https://huggingface.co/api/models/{self.identifier}/revision/{self.revision}"


class _NoRedirects(HTTPRedirectHandler):
    def redirect_request(
        self, req: Any, fp: Any, code: int, msg: str, headers: Any, newurl: str
    ) -> Any:
        raise ValueError("Research redirects are refused")


def public_get(url: str, *, cancelled: Callable[[], bool] = lambda: False) -> dict[str, Any]:
    # URL is exclusively generated by validated Lookup; no tokens or arbitrary destinations.
    opener = build_opener(_NoRedirects())
    deadline = time.monotonic() + 15
    chunks, size = [], 0
    with opener.open(
        Request(url, headers={"Accept": "application/json", "User-Agent": "StableNew-Evidence/1"}),
        timeout=2,
    ) as response:
        while True:
            if cancelled() or time.monotonic() >= deadline:
                raise TimeoutError("Research cancelled or deadline reached")
            # read1 returns available bytes rather than waiting to fill a large buffer.
            chunk = response.read1(min(16384, MAX_BYTES + 1 - size))
            if not chunk:
                break
            chunks.append(chunk)
            size += len(chunk)
            if size > MAX_BYTES:
                raise ValueError("Response exceeds limit")
    raw = b"".join(chunks)
    if len(raw) > MAX_BYTES:
        raise ValueError("Response exceeds limit")
    data = json.loads(raw)
    if not isinstance(data, dict):
        raise ValueError("Response must be an object")
    return data


class EvidenceRefresh:
    def __init__(
        self,
        get: Callable[[str], dict[str, Any]] = public_get,
        clock: Callable[[], float] = time.monotonic,
    ) -> None:
        self.get, self.clock = get, clock
        self._next_lookup = 0.0

    def refresh(
        self, lookup: Lookup, *, confirmed: bool, cancelled: Callable[[], bool] = lambda: False
    ) -> dict[str, Any]:
        if confirmed is not True:
            raise ValueError("Confirm the displayed disclosure before lookup")
        if cancelled():
            return {"status": "cancelled"}
        if self.clock() < self._next_lookup:
            return {
                "status": "rate_limited",
                "retry_after_seconds": max(1, int(self._next_lookup - self.clock())),
            }
        self._next_lookup = self.clock() + 2
        try:
            data = (
                public_get(lookup.url, cancelled=cancelled)
                if self.get is public_get
                else self.get(lookup.url)
            )
            if not isinstance(data, dict) or len(json.dumps(data, allow_nan=False)) > MAX_BYTES:
                raise ValueError("Invalid response")
            if cancelled():
                return {"status": "cancelled"}
            matched = False
            if lookup.service == "civitai":
                files = data.get("files", [])
                if not isinstance(files, list) or len(files) > 256:
                    raise ValueError("Invalid Civitai files")
                matched = any(
                    isinstance(f, dict)
                    and isinstance(f.get("hashes"), dict)
                    and str(f["hashes"].get("SHA256", "")).lower() == lookup.identifier
                    for f in files
                )
            elif data.get("sha") != lookup.revision:
                raise ValueError("Repository revision mismatch")
            # Drop arbitrary external metadata (and embedded prompts/URLs). A reviewer
            # must explicitly author field claims; neither API response is a recipe.
            return {
                "status": "candidate",
                "source": lookup.url,
                "identifier": lookup.identifier,
                "revision": lookup.revision,
                "hash_matched": matched,
                "model_version_id": data.get("id")
                if lookup.service == "civitai" and isinstance(data.get("id"), int)
                else None,
                "recommendation_status": "unreviewed; no executable defaults imported",
            }
        except HTTPError as exc:
            if exc.code == 429:
                retry = exc.headers.get("Retry-After", "60") if exc.headers else "60"
                seconds = min(3600, max(2, int(retry))) if str(retry).isdigit() else 60
                self._next_lookup = self.clock() + seconds
                return {"status": "rate_limited", "retry_after_seconds": seconds}
            return {"status": "service_error", "http_status": exc.code}
        except (OSError, ValueError, TypeError, RecursionError):
            return {
                "status": "unavailable",
                "reason": "Offline, timeout or invalid source response; prior evidence preserved.",
            }
