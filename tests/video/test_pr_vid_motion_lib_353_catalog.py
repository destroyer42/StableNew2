def test_importing_a_video_links_the_original_without_touching_it(tmp_path: Path) -> None:
    store = new_store(tmp_path)
    clip = write_clip(tmp_path / "in" / "Walk Cycle.mp4")
    before = (clip.read_bytes(), clip.stat().st_mtime_ns)
    inspector = FakeInspector(facts(width=640, height=360, fps=30.0, frames=60, seconds=2.0))

    outcome = import_video(
        store,
        clip,
        annotations={"tags": "Walking, Full Body", "source_category": SOURCE_OWNER_RECORDED},
        inspect=inspector,
    )

    assert outcome.status == OUTCOME_IMPORTED
    asset = store.require(outcome.asset_id)
    assert asset.sha256 == _sha(clip)
    assert asset.display_name == "Walk Cycle"
    assert asset.tags == ("walking", "full-body")
    assert (asset.width, asset.height, asset.fps, asset.frame_count) == (640, 360, 30.0, 60)
    assert asset.duration_seconds == 2.0
    assert asset.locator.mode == LOCATOR_LINKED and asset.locator.path == str(clip.resolve())
    assert asset.review_status == "unreviewed" and asset.imported_at.endswith("Z")
    assert store.thumbnail_path(asset) is not None and store.thumbnail_path(asset).is_file()
    assert (clip.read_bytes(), clip.stat().st_mtime_ns) == before
    assert not store.managed_dir.exists()


