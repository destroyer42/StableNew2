def test_a_corrupt_or_newer_manifest_is_refused_and_never_overwritten(tmp_path: Path) -> None:
    root = tmp_path / "library"
    root.mkdir()
    manifest = root / MANIFEST_NAME

    manifest.write_text("{ truncated", encoding="utf-8")
    with pytest.raises(LibraryCorruptError):
        MotionLibraryStore(root)
    assert manifest.read_text(encoding="utf-8") == "{ truncated"

    newer = json.dumps({"schema": "stablenew.motion-library", "version": 99, "assets": []})
    manifest.write_text(newer, encoding="utf-8")
    with pytest.raises(LibraryVersionError):
        MotionLibraryStore(root)
    assert manifest.read_text(encoding="utf-8") == newer


