def test_search_filters_return_exactly_the_matching_assets(tmp_path: Path) -> None:
    store, ids = _populate(tmp_path)

    def names(**query) -> list[str]:
        return [a.display_name for a in search_assets(store.assets(), SearchQuery(**query))]

    assert names() == ["dog run", "mixamo dance", "walk forward"]
    assert names(text="DANCE") == ["mixamo dance"]
    assert names(text="walk human") == ["walk forward"]
    assert names(tags=("Human",)) == ["mixamo dance", "walk forward"]
    assert names(source_categories=(SOURCE_STOCK_FOOTAGE, SOURCE_RENDERED_MOCAP)) == [
        "dog run",
        "mixamo dance",
    ]
    assert names(subject_kind="nonhuman") == ["dog run"]
    assert names(subject_count=2) == ["mixamo dance"]
    assert names(framing="full_body") == ["walk forward"]
    assert names(viewpoint="side") == ["mixamo dance"]
    assert names(camera_movement="tracking") == ["dog run"]
    assert names(motion_intensity="high") == ["dog run", "mixamo dance"]
    assert names(loop="loopable") == ["walk forward"] and names(loop="one_shot") == ["dog run"]
    assert names(review="reviewed") == ["mixamo dance", "walk forward"]
    assert names(review="unreviewed") == ["dog run"]
    assert names(good_for_motion_only=True) == ["walk forward"]
    assert names(min_seconds=0.5, max_seconds=2.0) == ["dog run", "mixamo dance", "walk forward"]
    assert names(min_seconds=5.0) == []
    assert names(min_frames=24, max_frames=24) == ["dog run", "mixamo dance", "walk forward"]
    assert names(min_frames=25) == []
    assert names(text="walk", review="unreviewed") == []
    assert known_tags(store.assets()) == ("animal", "dance", "human", "run", "walk")
    assert set(ids) == {"walk forward", "dog run", "mixamo dance"}


