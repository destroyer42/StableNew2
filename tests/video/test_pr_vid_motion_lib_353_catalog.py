def test_duplicate_bytes_share_one_identity_and_keep_every_alias_and_tag(tmp_path: Path) -> None:
    store = new_store(tmp_path)
    first = write_clip(tmp_path / "a" / "first.mp4")
    second = tmp_path / "b" / "renamed copy.mp4"
    second.parent.mkdir()
    second.write_bytes(first.read_bytes())
    inspector = FakeInspector()

    one = import_video(store, first, annotations={"tags": ["walk"]}, inspect=inspector)
    two = import_video(
        store,
        second,
        annotations={"tags": ["Stock", "walk"], "source_reference": "pexels 123"},
        inspect=inspector,
    )

    assert two.status == OUTCOME_DUPLICATE and two.asset_id == one.asset_id
    assert len(store) == 1 and len(inspector.calls) == 1  # the duplicate was never re-inspected
    asset = store.require(one.asset_id)
    assert asset.tags == ("walk", "stock")
    assert [a.path for a in asset.aliases] == [str(second.resolve())]
    assert asset.aliases[0].source_reference == "pexels 123"
    again = import_video(store, second, inspect=inspector)
    assert again.status == OUTCOME_DUPLICATE and len(store.require(one.asset_id).aliases) == 1


