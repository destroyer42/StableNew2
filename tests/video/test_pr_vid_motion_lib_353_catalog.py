def test_missing_changed_and_replaced_files_are_never_accepted_as_the_original(
    tmp_path: Path,
) -> None:
    store = new_store(tmp_path)
    clip = write_clip(tmp_path / "in" / "walk.mp4")
    asset = store.require(import_video(store, clip, inspect=FakeInspector()).asset_id)
    path = store.asset_path(asset)

    assert quick_check(asset, path).state == FILE_UNVERIFIED  # never "ok" without hashing
    assert verify_content(asset, path).state == FILE_OK

    clip.write_bytes(clip.read_bytes() + b"x")  # replaced in place
    assert quick_check(asset, path).state == FILE_CHANGED
    assert verify_content(asset, path).state == FILE_CHANGED

    moved = clip.rename(tmp_path / "in" / "moved.mp4")
    assert quick_check(asset, path).state == FILE_MISSING
    assert verify_content(asset, path).state == FILE_MISSING
    assert moved.exists()


def test_relink_requires_the_same_bytes_and_keeps_the_old_path(tmp_path: Path) -> None:
    store = new_store(tmp_path)
    clip = write_clip(tmp_path / "in" / "walk.mp4")
    asset_id = import_video(store, clip, inspect=FakeInspector()).asset_id
    original_path = str(clip.resolve())
    (tmp_path / "moved").mkdir()
    moved = clip.rename(tmp_path / "moved" / "walk renamed.mp4")

    wrong = write_clip(tmp_path / "moved" / "other.mp4", b"different bytes")
    refused = relink_asset(store, asset_id, wrong)
    assert not refused.ok and "differ" in refused.reason
    assert store.require(asset_id).locator.path == original_path

    accepted = relink_asset(store, asset_id, moved)
    assert accepted.ok
    asset = store.require(asset_id)
    assert asset.locator.path == str(moved.resolve())
    assert original_path in [a.path for a in asset.aliases]
    assert verify_content(asset, store.asset_path(asset)).state == FILE_OK
    assert not relink_asset(store, asset_id, tmp_path / "missing.mp4").ok
    assert not relink_asset(store, asset_id, tmp_path / "moved" / "x.avi").ok


