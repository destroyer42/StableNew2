def test_folder_import_is_flat_reports_each_failure_and_ignores_other_files(tmp_path: Path) -> None:
    store = new_store(tmp_path)
    folder = tmp_path / "pack"
    write_clip(folder / "a.mp4", b"a")
    write_clip(folder / "b.webm", b"b")
    write_clip(folder / "nested" / "deep.mp4", b"deep")  # sub-folders are out of scope
    (folder / "notes.txt").write_text("hello", encoding="utf-8")
    (folder / "old.avi").write_bytes(b"avi")
    (folder / ".hidden.mp4").write_bytes(b"hidden")
    broken = write_clip(folder / "broken.mp4", b"broken")
    inspector = FakeInspector()

    class Selective(FakeInspector):
        def __call__(self, path, cancel=None):
            if Path(path).name == "broken.mp4":
                return FakeInspector(failure="not a video")(path, cancel)
            return inspector(path, cancel)

    report = import_folder(store, folder, inspect=Selective())

    by_name = {Path(o.path).name: o for o in report.outcomes}
    assert set(by_name) == {"a.mp4", "b.webm", "broken.mp4", "old.avi"}
    assert (
        by_name["a.mp4"].status == OUTCOME_IMPORTED and by_name["b.webm"].status == OUTCOME_IMPORTED
    )
    assert (
        by_name["broken.mp4"].status == OUTCOME_FAILED
        and "not a video" in by_name["broken.mp4"].reason
    )
    assert (
        by_name["old.avi"].status == OUTCOME_FAILED and "Unsupported" in by_name["old.avi"].reason
    )
    assert (
        report.ignored_non_video == 3
    )  # notes.txt, the hidden file and the nested/ folder (not entered)
    assert (report.imported, report.failed) == (2, 2)
    assert len(store) == 2 and broken.exists()
    assert "2 imported" in report.summary()


def test_folder_import_is_bounded_and_cancellable(tmp_path: Path) -> None:
    import threading

    store = new_store(tmp_path)
    folder = tmp_path / "pack"
    for i in range(5):
        write_clip(folder / f"c{i}.mp4", bytes([i]))
    report = import_folder(store, folder, max_files=3, inspect=FakeInspector())
    assert report.truncated and report.imported == 3

    stop = threading.Event()
    stop.set()
    cancelled = import_folder(store, folder, inspect=FakeInspector(), cancel=stop)
    assert cancelled.cancelled and cancelled.outcomes == ()

    missing = import_folder(store, tmp_path / "nowhere", inspect=FakeInspector())
    assert missing.failed == 1


