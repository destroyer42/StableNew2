def test_an_interrupted_import_leaves_the_manifest_and_originals_intact(
    tmp_path: Path, monkeypatch
) -> None:
    store = new_store(tmp_path)
    keep = write_clip(tmp_path / "in" / "keep.mp4", b"keep")
    import_video(store, keep, inspect=FakeInspector())
    manifest_before = store.manifest_path.read_text(encoding="utf-8")
    clip = write_clip(tmp_path / "in" / "walk.mp4", b"other bytes")

    def failing_write(*_a, **_k):
        raise OSError("disk full")

    monkeypatch.setattr("src.video.motion_library.store.atomic_write_json", failing_write)
    outcome = import_video(store, clip, mode=LOCATOR_MANAGED, inspect=FakeInspector())

    assert outcome.status == OUTCOME_FAILED and "disk full" in outcome.reason
    assert store.manifest_path.read_text(encoding="utf-8") == manifest_before
    assert len(store) == 1  # in-memory state rolled back with the disk
    assert list(store.managed_dir.iterdir()) == []  # the copy this import made was removed
    assert clip.exists()


