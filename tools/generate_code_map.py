"""Generate ``docs/CODE_MAP.md``: one line per ``src`` module, taken from the module docstring.

The map is derived, never hand-edited, so it cannot drift from the code. ``tests/tools/test_code_map.py`` fails when the
committed file differs from what this script produces. Line counts are deliberately left out so the file only changes when
a module is added, removed, renamed or re-described.

    python tools/generate_code_map.py            # rewrite docs/CODE_MAP.md
    python tools/generate_code_map.py --check    # exit 1 when the committed file is stale
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = "src"
OUTPUT = "docs/CODE_MAP.md"
SUMMARY_LIMIT = 110
NO_DOCSTRING = "(no docstring)"
UNPARSEABLE = "(could not be parsed)"


def summarize(source: str) -> str:
    """First sentence of the module docstring, flattened to one line and capped."""
    try:
        docstring = ast.get_docstring(ast.parse(source))
    except SyntaxError:
        return UNPARSEABLE
    if not docstring:
        return NO_DOCSTRING
    paragraph = " ".join(docstring.strip().split("\n\n", 1)[0].split())
    sentence = paragraph.split(". ", 1)[0].rstrip(".")
    if len(sentence) > SUMMARY_LIMIT:
        sentence = sentence[: SUMMARY_LIMIT - 1].rstrip() + "…"
    return sentence.replace("|", "/")


def module_files(root: Path = ROOT) -> list[Path]:
    return sorted(
        (path for path in (root / SOURCE).rglob("*.py") if "__pycache__" not in path.parts),
        key=lambda path: path.relative_to(root).as_posix(),
    )


def render(root: Path = ROOT) -> str:
    groups: dict[str, list[tuple[str, str]]] = {}
    documented = 0
    total = 0
    for path in module_files(root):
        relative = path.relative_to(root).as_posix()
        directory, _, name = relative.rpartition("/")
        summary = summarize(path.read_text(encoding="utf-8"))
        groups.setdefault(directory, []).append((name, summary))
        total += 1
        documented += summary not in (NO_DOCSTRING, UNPARSEABLE)
    lines = [
        "# StableNew code map",
        "",
        "<!-- GENERATED by tools/generate_code_map.py. Do not edit by hand. -->",
        "",
        "One line per module under `src/`, taken from its docstring. Regenerate with `python tools/generate_code_map.py`;",
        "`tests/tools/test_code_map.py` fails when this file is stale. To improve an entry, edit the module docstring.",
        "For where to start on a task, use `docs/CODEX_MAP.md`.",
        "",
        f"{documented} of {total} modules have a docstring.",
    ]
    for directory in sorted(groups):
        lines += ["", f"## {directory}/", ""]
        lines += [f"- `{name}`: {summary}" for name, summary in groups[directory]]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail instead of writing when the committed map is stale",
    )
    args = parser.parse_args(argv)
    target = ROOT / OUTPUT
    rendered = render()
    current = target.read_text(encoding="utf-8") if target.is_file() else None
    if args.check:
        if current != rendered:
            print(f"{OUTPUT} is stale; run: python tools/generate_code_map.py", file=sys.stderr)
            return 1
        return 0
    if current != rendered:
        target.write_text(rendered, encoding="utf-8", newline="\n")
        print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
